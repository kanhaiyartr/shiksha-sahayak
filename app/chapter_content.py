def get_pack(language: str, topic: str) -> Pack | None:
    table = HI if language == "hi" else EN
    return table.get(topic)


def pack_for_hint(language: str, topic: str) -> dict[str, str]:
    """Flatten pack fields for the syllabus tool / Claude grounding."""

    pack = get_pack(language, topic)
    if pack is None:
        return {}
    return {
        "definition": pack["definition"],
        "facts": " | ".join(pack["facts"]),
        "examples": " | ".join(pack["examples"]),
        "sample_questions": " || ".join(
            f"Q: {item['prompt']} A: {item['answer']}" for item in pack["questions"][:4]
        ),
        "teacher_tip": pack["tip"],
    }
